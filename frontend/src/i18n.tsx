interface Locale {
  lang: "en" | "ar";
  toggle: () => void;
  t: (key: string) => string;
}
const Context = createContext<Locale>({
  lang: "en",
  toggle: () => {},
  t: (k) => k,
});
export function Language({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<"en" | "ar">(() =>
    localStorage.getItem("gold-language") === "ar" ? "ar" : "en",
  );
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    window.scrollTo({ left: 0, top: window.scrollY, behavior: "instant" });
    localStorage.setItem("gold-language", lang);
  }, [lang]);
  return (
    <Context.Provider
      value={{
        lang,
        toggle: () => setLang(lang === "en" ? "ar" : "en"),
        t: (k) => (lang === "ar" ? ar[k] || k : k),
      }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
